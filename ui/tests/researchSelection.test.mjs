import assert from "node:assert/strict";
import test from "node:test";
import { researchSelection } from "../src/researchSelection.ts";
const available=[{id:"codex"},{id:"claude-code"}];
const choice=(model,harness="codex")=>({harness,model,reasoningLevel:"max",serviceTier:null,permissionMode:null});
const job={harness:"codex",model:"old-model",reasoningLevel:"medium"};
test("folder's changed model survives restoration of a job generated by another model",()=>{
  const a=choice("new-model");const b=choice("folder-b");
  assert.deepEqual(researchSelection(available,a,job,b),a);
  assert.deepEqual(researchSelection(available,b,job,a),b);
  assert.equal(job.model,"old-model");
});
test("legacy folders inherit historical provenance before a global preference",()=>{
  assert.equal(researchSelection(available,null,job,choice("global")).model,"old-model");
  assert.equal(researchSelection(available,null,null,choice("global")).model,"global");
});
test("explicit CLI default and different ready harness are preserved",()=>{
  assert.equal(researchSelection(available,choice(null),job,null).model,null);
  assert.equal(researchSelection(available,choice("other","claude-code"),job,null).harness,"claude-code");
  assert.equal(researchSelection(available,choice("gone","missing"),job,null).model,"old-model");
  assert.equal(researchSelection([],choice("gone"),job,null),null);
});
